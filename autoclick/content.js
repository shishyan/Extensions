(() => {
  if (document.getElementById("autoclick-pill")) return;

  let clickTimer = null;
  let clickCount = 0;

  function fillAllForms() {
    let filled = 0;
    document.querySelectorAll("input, textarea, select").forEach((el) => {
      if (el.disabled || el.readOnly) return;
      const tag = el.tagName.toLowerCase();
      const type = (el.getAttribute("type") || "text").toLowerCase();
      const name = ((el.name || el.id || el.placeholder || "") + "").toLowerCase();

      if (tag === "select") {
        if (el.options && el.options.length > 1) {
          el.selectedIndex = 1;
          el.dispatchEvent(new Event("change", { bubbles: true }));
          filled++;
        }
        return;
      }
      if (tag === "textarea") {
        el.value = "Synthetic QA test payload generated by AutoClick & QA Form Filler.";
        el.dispatchEvent(new Event("input", { bubbles: true }));
        filled++;
        return;
      }
      if (["hidden", "submit", "button", "reset", "file", "image"].includes(type)) return;
      if (type === "checkbox" || type === "radio") {
        el.checked = true;
        el.dispatchEvent(new Event("change", { bubbles: true }));
        filled++;
        return;
      }
      if (type === "email" || name.includes("email")) {
        el.value = "qa.engineer@gurukuladesam.org";
      } else if (type === "tel" || name.includes("phone")) {
        el.value = "+1-415-555-0199";
      } else if (type === "url" || name.includes("url") || name.includes("website")) {
        el.value = "https://gurukuladesam.org/qa-suite";
      } else if (type === "number") {
        el.value = "42";
      } else if (type === "date") {
        el.value = "2026-11-01";
      } else {
        el.value = "Ada Lovelace QA";
      }
      el.dispatchEvent(new Event("input", { bubbles: true }));
      el.dispatchEvent(new Event("change", { bubbles: true }));
      filled++;
    });
    return filled;
  }

  function triggerAutoClick(selector, intervalMs = 500) {
    if (clickTimer) {
      clearInterval(clickTimer);
      clickTimer = null;
      return { running: false, clickCount };
    }
    const target = document.querySelector(selector);
    if (target) {
      target.click();
      clickCount++;
    }
    clickTimer = setInterval(() => {
      const el = document.querySelector(selector);
      if (el) {
        el.click();
        clickCount++;
      }
    }, Math.max(100, Number(intervalMs) || 500));
    return { running: true, clickCount };
  }

  const pill = document.createElement("div");
  pill.id = "autoclick-pill";
  pill.innerHTML = `
    <span class="ac-label">⚡ AutoClick &amp; QA Form Filler</span>
    <button type="button" id="autoclick-fill-btn">Fill Forms</button>
    <button type="button" id="autoclick-run-btn">Auto-Click</button>
  `;
  document.body.appendChild(pill);

  const fillBtn = document.getElementById("autoclick-fill-btn");
  const runBtn = document.getElementById("autoclick-run-btn");

  fillBtn.addEventListener("click", () => {
    const count = fillAllForms();
    fillBtn.textContent = `✓ Filled (${count})`;
    setTimeout(() => {
      fillBtn.textContent = "Fill Forms";
    }, 1500);
  });

  runBtn.addEventListener("click", () => {
    const res = triggerAutoClick("[data-autoclick-target], #qa-action-btn, button", 500);
    runBtn.textContent = res.running ? `⏹ Stop (${res.clickCount})` : "Auto-Click";
  });

  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg && msg.type === "AUTOCLICK_FILL_FORMS") {
      const filled = fillAllForms();
      sendResponse({ ok: true, filled });
      return true;
    }
    if (msg && msg.type === "AUTOCLICK_TOGGLE_CLICKER") {
      const res = triggerAutoClick(msg.selector || "#qa-action-btn", msg.intervalMs || 500);
      sendResponse({ ok: true, running: res.running, clickCount: res.clickCount });
      return true;
    }
  });
})();
